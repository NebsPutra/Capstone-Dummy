const id: Dict = { ...idBase, ...idExtra };

export const translations: Record<Lang, Dict> = { en, id };

export type TranslateVars = Record<string, string | number>;

export function translate(lang: Lang, key: TranslationKey, vars?: TranslateVars): string {
  let text: string = translations[lang][key] ?? translations.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

/** Translate a dynamic key (e.g. `status.${value}`) when it may not exist. */
export function translateDynamic(lang: Lang, key: string, fallback: string): string {
  return key in translations[lang] ? translations[lang][key as TranslationKey] : fallback;
}

export function isLang(v: unknown): v is Lang {
  return v === "en" || v === "id";
}
